export type Update = typeof UPDATES[number];

export function ogUrl(u: Update, base = '') {
  const p = new URLSearchParams({
    product: u.product,
    version: u.version,
    title:   u.title,
    tagline: u.tagline,
    date:    u.date,
  });
  return `${base}/api/og?${p.toString()}`;
}
